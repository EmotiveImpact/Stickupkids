"""The job board's map of London: the Thames, trunk roads and parks, drawn
from OpenStreetMap as one small SVG for src/ui/cityMap.ts.

Reads art/osm/london-raw.json (and burgess-raw.json for the outline of
Burgess Park); neither raw file is committed, see art/osm/README.md.

Map data © OpenStreetMap contributors, available under the Open Database
Licence (https://www.openstreetmap.org/copyright).

Run: python3 art/osm/citymap.py
"""
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src", "ui", "cityMap.ts")

# West, south, east, north.
BOX = (-0.262, 51.448, 0.012, 51.552)
W = 720
LAT0 = (BOX[1] + BOX[3]) / 2
KX = math.cos(math.radians(LAT0))
H = round(W * (BOX[3] - BOX[1]) / ((BOX[2] - BOX[0]) * KX))


def px(lat, lon):
    return ((lon - BOX[0]) / (BOX[2] - BOX[0]) * W, (BOX[3] - lat) / (BOX[3] - BOX[1]) * H)


def simplify(pts, tol):
    """Douglas-Peucker. A closed ring is split at its far point first."""
    if len(pts) < 3:
        return pts
    if pts[0] == pts[-1]:
        far = max(range(len(pts)), key=lambda i: math.hypot(pts[i][0] - pts[0][0], pts[i][1] - pts[0][1]))
        return simplify(pts[: far + 1], tol)[:-1] + simplify(pts[far:], tol)
    a, b = pts[0], pts[-1]
    dx, dy = b[0] - a[0], b[1] - a[1]
    L = math.hypot(dx, dy) or 1e-9
    best, bi = -1, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * (pts[i][0] - a[0]) - dx * (pts[i][1] - a[1])) / L
        if d > best:
            best, bi = d, i
    if best <= tol:
        return [a, b]
    return simplify(pts[: bi + 1], tol)[:-1] + simplify(pts[bi:], tol)


def d_attr(pts, close=False):
    s = "M" + "L".join(f"{x:.0f} {y:.0f}" for x, y in pts)
    return s + ("Z" if close else "")


def length(pts):
    return sum(math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]) for i in range(1, len(pts)))


def inside(pts):
    return any(-20 <= x <= W + 20 and -20 <= y <= H + 20 for x, y in pts)


def main():
    raw = json.load(open(os.path.join(HERE, "london-raw.json")))
    river, roads, parks = [], [], []
    for e in raw["elements"]:
        t = e.get("tags", {})
        g = e.get("geometry") or []
        pts = [px(q["lat"], q["lon"]) for q in g]
        if len(pts) < 2 or not inside(pts):
            continue
        if t.get("waterway") == "river":
            river.append(d_attr(simplify(pts, 0.6)))
        elif t.get("highway") in ("motorway", "trunk") and length(pts) > 4:
            roads.append(d_attr(simplify(pts, 1.2)))
        elif t.get("leisure") == "park" and len(pts) > 3:
            s = simplify(pts, 0.7)
            area = 0.5 * abs(sum(s[i][0] * s[i - 1][1] - s[i - 1][0] * s[i][1] for i in range(len(s))))
            if area > 6:
                parks.append(d_attr(s, True))
    burgess = []
    for e in json.load(open(os.path.join(HERE, "burgess-raw.json")))["elements"]:
        t = e.get("tags", {})
        if t.get("name") == "Burgess Park" and e["type"] == "relation":
            for m in e["members"]:
                if m.get("role") == "outer" and m.get("geometry"):
                    burgess.append(d_attr(simplify([px(q["lat"], q["lon"]) for q in m["geometry"]], 0.4)))
    with open(OUT, "w") as f:
        f.write("// Generated by art/osm/citymap.py from OpenStreetMap data. Do not edit.\n")
        f.write("// Map data © OpenStreetMap contributors, available under the Open Database Licence.\n\n")
        f.write(f"export const MAP_W = {W};\nexport const MAP_H = {H};\n")
        f.write(f"const BOX = {list(BOX)};\n\n")
        f.write("/** Map position of a point given in degrees. */\n")
        f.write("export function mapXY(lat: number, lon: number): [number, number] {\n")
        f.write("  return [((lon - BOX[0]) / (BOX[2] - BOX[0])) * MAP_W, ((BOX[3] - lat) / (BOX[3] - BOX[1])) * MAP_H];\n}\n\n")
        for name, items in (("RIVER", river), ("ROADS", roads), ("PARKS", parks), ("BURGESS", burgess)):
            f.write(f"export const {name} = {json.dumps(' '.join(items))};\n")
    print(OUT, W, H, len(river), len(roads), len(parks), f"{os.path.getsize(OUT) / 1e3:.0f} kB")


main()
